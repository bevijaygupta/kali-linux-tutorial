def build_readme_table(videos: list[dict], curricula: dict[str, dict]) -> str:
    modules: dict[str, list[dict]] = {}
    for video in sorted(videos, key=lambda item: int(item["chapter"])):
        module = (curricula.get(str(video["chapter"])) or {}).get("module") or video.get("module") or "Course"
        modules.setdefault(module, []).append(video)

    total = len(videos)
    published = sum(1 for video in videos if video.get("status") == "published")
    lines = [
        f"The table follows the teaching order, not the playlist order. YouTube shows the newest "
        f"chapter first; this repository keeps the original position in `data/playlist.json`. "
        f"**{total} chapters** are listed: **{published} published**, **{total - published} scheduled**.",
        "",
    ]
    for module, items in modules.items():
        lines.append(f"### {module}")
        lines.append("")
        lines.append("| Lesson | Topic | Learning Description | Watch Tutorial |")
        lines.append("| ---: | --- | --- | --- |")
        for video in items:
            chapter = int(video["chapter"])
            curriculum = curricula.get(str(chapter)) or {}
            topic = clean_title(video["title"]).replace("|", "\\|")
            learn = (curriculum.get("learn") or [""])[0].replace("|", "\\|")
            lesson_link = f"[Lesson {chapter}](lessons/lesson-{chapter:03d}.md)"
            if video.get("status") == "published":
                watch = f"[YouTube]({video['url']}) · {video.get('duration') or 'watch'}"
            else:
                watch = "Scheduled — notes ready"
            lines.append(f"| {lesson_link} | {topic} | {learn} | {watch} |")
        lines.append("")
    return "\n".join(lines)


def update_readme(table: str) -> bool:
    if not README.exists():
        raise SystemExit("README.md is missing; create it with CURRICULUM:START/END markers first")
    text = README.read_text(encoding="utf-8")
    if CURRICULUM_START not in text or CURRICULUM_END not in text:
        raise SystemExit("README.md is missing the CURRICULUM markers")
    start = text.index(CURRICULUM_START) + len(CURRICULUM_START)
    end = text.index(CURRICULUM_END)
    new_text = text[:start] + "\n" + table.rstrip() + "\n" + text[end:]
    if new_text != text:
        README.write_text(new_text, encoding="utf-8", newline="\n")
        return True
    return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args()

    playlist = load_json(DATA_DIR / "playlist.json")
    curricula = load_json(DATA_DIR / "curriculum.json")
    videos = playlist["videos"]
    videos_by_chapter = {int(video["chapter"]): video for video in videos}

    missing = sorted(set(range(1, len(videos) + 1)) - set(videos_by_chapter))
    if missing:
        raise SystemExit(f"playlist is missing chapters: {missing}")
    orphan_curricula = sorted(set(curricula) - {str(chapter) for chapter in videos_by_chapter})
    if orphan_curricula:
        raise SystemExit(f"curriculum.json has entries without videos: {orphan_curricula}")

    LESSONS_DIR.mkdir(exist_ok=True)
    changed: list[str] = []
    for chapter in sorted(videos_by_chapter):
        path = LESSONS_DIR / f"lesson-{chapter:03d}.md"
        content = build_lesson(videos_by_chapter[chapter], curricula.get(str(chapter), {}), videos_by_chapter)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            changed.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content, encoding="utf-8", newline="\n")

    index_path = LESSONS_DIR / "index.md"
    index_content = build_lessons_index(videos, curricula)
    if not index_path.exists() or index_path.read_text(encoding="utf-8") != index_content:
        changed.append(str(index_path.relative_to(ROOT)))
        if not args.check:
            index_path.write_text(index_content, encoding="utf-8", newline="\n")

    table = build_readme_table(videos, curricula)
    if README.exists():
        text = README.read_text(encoding="utf-8")
        start = text.index(CURRICULUM_START) + len(CURRICULUM_START) if CURRICULUM_START in text else -1
        end = text.index(CURRICULUM_END) if CURRICULUM_END in text else -1
        current = text[start:end].strip() if start >= 0 and end > start else ""
        if current != table.strip():
            changed.append("README.md curriculum table")
            if not args.check:
                update_readme(table)
    else:
        changed.append("README.md missing")

    if args.check and changed:
        print("Generated files are out of date:")
        for item in changed:
            print(f"  - {item}")
        print("Run: python scripts/generate_lesson_pages.py")
        return 1

    if changed:
        print(f"Updated {len(changed)} generated file(s):")
        for item in changed:
            print(f"  - {item}")
    else:
        print(f"All {len(videos)} lesson pages, the lessons index and the README table are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
