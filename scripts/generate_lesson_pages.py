def load_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def yaml_string(value: str) -> str:
    """Return a JSON string, which is valid YAML for front matter scalars."""
    return json.dumps(value, ensure_ascii=False)


def clean_title(raw: str) -> str:
    """Remove chapter suffixes, years and hashtags from a YouTube title."""
    parts = [part.strip() for part in raw.split("|")]
    kept = []
    for part in parts:
        if not part:
            continue
        if re.match(r"^(ch\.?|chapter)\s*\d+\b", part, re.I):
            continue
        if re.match(r"^\d{4}\b", part) and (len(part) <= 30 or re.fullmatch(r"\d{4}(\s+#\w+)*", part)):
            continue
        if part.startswith("#"):
            continue
        if re.search(r"\b(chapter|ch\.?)\s*\d+\b", part, re.I) and (
            "kali" in part.lower() or "course" in part.lower() or len(part) < 40
        ):
            continue
        kept.append(part)
    title = " | ".join(kept) if kept else raw
    title = re.sub(r"\s+#\w+", "", title)
    title = re.sub(r"\s+(ch\.?|chapter)\s*\d+\s*$", "", title, flags=re.I)
    title = re.sub(r"\s+", " ", title).strip(" |-")
    return title


def first_sentence(text: str, limit: int = 220) -> str:
    """Pick an informative sentence, skipping boilerplate intros."""
    paragraphs = [re.sub(r"\s+", " ", block).strip() for block in re.split(r"\n\s*\n", text or "")]
    boilerplate = re.compile(
        r"^(chapter \d+ of our|welcome|in this (video|chapter)|this (video|chapter) is part|"
        r"in this tutorial|subscribe|disclaimer)",
        re.I,
    )
    candidates = [block for block in paragraphs if block and not boilerplate.match(block)]
    text = " ".join(candidates) or re.sub(r"\s+", " ", text or "").strip()
    if not text:
        return ""
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    if len(sentence) < 80 and len(candidates) > 1:
        sentence = text
    if len(sentence) > limit:
        sentence = sentence[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return sentence


def iso_duration(seconds: int | None) -> str | None:
    if not seconds:
        return None
    hours, rest = divmod(int(seconds), 3600)
    minutes, secs = divmod(rest, 60)
    out = "PT"
    if hours:
        out += f"{hours}H"
    if minutes:
        out += f"{minutes}M"
    if secs or out == "PT":
        out += f"{secs}S"
    return out


def human_date(value: str | None) -> str:
    if not value:
        return ""
    try:
        parsed = dt.date.fromisoformat(value)
    except ValueError:
        return value
    return parsed.strftime("%B %-d, %Y") if sys.platform != "win32" else parsed.strftime("%B %d, %Y").replace(" 0", " ")


def collect_resources(video: dict, curriculum: dict) -> list[tuple[str, str]]:
    haystack = " ".join(
        [
            video.get("title", ""),
            video.get("module", ""),
            " ".join(curriculum.get("tags", [])),
            " ".join(concept.get("h", "") + " " + concept.get("p", "") for concept in curriculum.get("concepts", [])),
        ]
    ).lower()
    found: list[tuple[str, str]] = []
    seen: set[str] = set()
    for pattern, label, url in TOOL_LINKS:
        if re.search(pattern, haystack, re.I) and url not in seen:
            found.append((label, url))
            seen.add(url)
        if len(found) >= 4:
            break
    for label, url in ALWAYS_RESOURCES:
        if url not in seen and len(found) < 5:
            found.append((label, url))
            seen.add(url)
    found.append(("Full course playlist on YouTube", PLAYLIST_URL))
    return found


